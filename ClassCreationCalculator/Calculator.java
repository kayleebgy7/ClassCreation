package ClassCreationCalculator;

public class Calculator {
    public int addIntegers(int num1, int num2) {
        return num1 + num2;
    }

    public int subtractInt(int num1, int num2) {
        return num1 - num2;
    }




    public int multiply(int num1, int num2) {
        return num1 * num2;
    }




    public int divideInt(int num1, int num2) {
        return num1/num2;
    }




    public double addIntegers(double num1, double num2) {
        return num1 + num2;
    }




    public double subtractInt(double num1, double num2) {
        return num1 - num2;
    }




    public double multiply(double num1, double num2) {
        return num1 * num2;
    }

    public double divideInt(double num1, double num2) {
        return num1 / num2;
    }
       
   
}
