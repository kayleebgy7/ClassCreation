    public int addIntegers(int num1, int num2) {
        return num1 + num2;
    }




    public int subtractInt(int num1, int num2) {
        return num1 - num2;
    }




    public int multiply(int num1, int num2) {
        return num1 * num2;
    }




    public int divideInt(int num1, int num2) {
        return num1/num2;
    }




